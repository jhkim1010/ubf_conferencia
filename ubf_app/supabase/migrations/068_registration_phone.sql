-- 068: 등록자 전화번호
--
-- 픽업과 배차에서 사람을 찾아야 하는데, 지금까지 등록에는 전화번호를 받는
-- 칸이 아예 없었다. 담당자 연락처(005)와 명함(031)에만 있었고 둘 다 참가자
-- 등록과는 다른 것이다.
--
-- **선택이다.** 텔레그램(047)으로 닿는 사람이 이미 많고, 필수로 만들면
-- 번호가 없거나 적기 싫은 사람이 등록 자체를 못 마친다.
--
-- 자동으로 채워 준다 — 지난 등록에 적어 둔 것이 있으면 그것, 없으면 명함에
-- 적어 둔 것. **채우기만 하고 고칠 수 있게 둔다.** 번호는 바뀌고, 우리가
-- 넣은 값을 못 고치게 하면 틀린 번호가 그대로 굳는다.
--
-- 구글 로그인은 전화번호를 주지 않는다. 별도 권한이 필요하고, 받아도
-- 계정에 번호를 넣어 둔 사람이 많지 않다. 그래서 "자동" 의 출처는 우리가
-- 이미 가진 값뿐이다.
ALTER TABLE registrations
  ADD COLUMN IF NOT EXISTS phone TEXT;

COMMENT ON COLUMN registrations.phone IS
  '참가자 전화번호. 선택이며 지난 등록·명함에서 채워 주되 고칠 수 있다(068)';
