--
-- 오류 문구는 요청이 들어온 그 자리에서 Accept-Language 를 보고 갈아 끼운다
-- (055). 알림은 그럴 수 없다 — 밤에 도는 크론이나 담당자의 행동으로 나가므로
-- 받는 사람이 그 자리에 없다. 그래서 **미리 적어 두어야** 한다.
--
-- 앱은 이미 요청마다 Accept-Language 를 보내고 있었다. 그것을 흘려보내지
-- 않고 로그인할 때 남긴다.
--
-- 비어 있으면 한국어로 본다. 한 번도 안 적힌 사람에게 엉뚱한 언어로 보내는
-- 것보다, 지금까지와 같게 두는 편이 낫다.
ALTER TABLE users ADD COLUMN IF NOT EXISTS ui_language TEXT;
