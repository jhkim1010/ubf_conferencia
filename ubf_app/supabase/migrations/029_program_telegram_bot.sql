-- 029: 수양회별 텔레그램 봇
--
-- 지금까지는 봇 토큰이 서버 환경변수 하나(TELEGRAM_BOT_TOKEN)뿐이라 모든
-- 수양회가 같은 봇을 썼다. 수양회마다 담당자가 다르고 단톡방도 다른데,
-- 봇을 바꾸려면 서버를 만지고 재시작해야 했다.
--
-- 이제 수양회를 만들 때 담당자가 자기 봇을 적어 두면 그 수양회의 알림은
-- 그 봇으로 나간다. 안 적으면 예전처럼 환경변수 봇을 쓴다.
--
-- chat_id 는 002 에서 이미 만들었다. 토큰만 더한다.
--
-- **이 값은 비밀이다.** 토큰을 아는 사람은 그 봇으로 아무 메시지나 보낼 수
-- 있다. 서버는 이 컬럼을 어떤 응답에도 실어 보내지 않는다 — 프로그램 조회는
-- 참가자도 부를 수 있는 경로다. 설정 여부만 불리언으로 알린다.
ALTER TABLE programs
  ADD COLUMN IF NOT EXISTS telegram_bot_token TEXT;

COMMENT ON COLUMN programs.telegram_bot_token IS
  '수양회 전용 텔레그램 봇 토큰. 비밀값이므로 API 응답에 절대 포함하지 않는다.';
