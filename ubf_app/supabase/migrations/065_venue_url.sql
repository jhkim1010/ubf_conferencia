-- 065: 장소 홈페이지
--
-- 장소는 지금까지 글자 한 줄이었다 — "Pilar, Buenos Aires, Argentin".
-- 처음 가는 사람은 그 이름만 들고 따로 찾아봐야 한다. 호텔 홈페이지든
-- 지도든, 담당자가 이미 알고 있는 주소를 한 번 적어 두면 될 일이다.
--
-- 참가자 화면에서는 **이미 장소가 나오는 자리**를 누르면 열린다. 새 줄을
-- 만들지 않는다 — 장소와 장소 링크가 따로 놓이면 둘이 같은 곳을 가리키는지
-- 알 수 없다.
--
-- 비워 두면 지금과 똑같다. 화면에 밑줄도 화살표도 안 생긴다.
--
-- 열 때는 http·https 인지 화면에서 한 번 더 본다. 여기서 CHECK 로 막지
-- 않는 이유는, 이미 적어 둔 값이 있을 때 제약을 붙이면 저장이 통째로
-- 막히기 때문이다. 못 여는 주소는 글자로만 보여준다.
--
-- 번호가 064 를 건너뛴다. 등록 순서를 바꾼 작업이 스키마를 안 바꿨는데
-- 코드 주석이 그 번호를 쓰고 있어서, 여기서 064 를 쓰면 번호가 가리키는
-- 것이 엇갈린다.
ALTER TABLE programs
  ADD COLUMN IF NOT EXISTS venue_url TEXT;

COMMENT ON COLUMN programs.venue_url IS
  '장소 홈페이지. 참가자 화면에서 장소를 누르면 열린다. 비우면 링크 없음(065)';
