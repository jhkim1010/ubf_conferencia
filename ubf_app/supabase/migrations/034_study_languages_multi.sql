-- 034: 참석자가 쓸 수 있는 언어를 여럿 적는다
--
-- 이 수양회에는 두세 언어를 하는 사람이 흔하다 — 아르헨티나에 사는 한인 2세,
-- 스페인어권에 파송된 한국인 선교사, 브라질에서 오는 한인 가정. 하나만
-- 고르게 하면 그 사실이 어디에도 남지 않는다.
--
-- **study_language(025)는 그대로 둔다.** 성경공부 팀은 한 사람이 한 곳에만
-- 앉으므로 배정에는 하나가 필요하다. 그것을 "주 언어"로 삼고, 여기에는
-- 고른 것을 순서대로 모두 담는다. 첫 번째가 곧 주 언어다.
--
-- 나중에 배정 엔진이 이 칸을 쓸 수 있다. 소수 인원 칸을 다른 언어 팀에
-- 억지로 합치는 대신(025 의 merge), 그 사람이 실제로 할 수 있는 언어의
-- 팀으로 보내면 된다. 지금은 기록만 한다 — 엔진을 함께 바꾸면 무엇 때문에
-- 배정이 달라졌는지 가려내기 어렵다.
ALTER TABLE registrations
  ADD COLUMN IF NOT EXISTS study_languages TEXT[] NOT NULL DEFAULT '{}';

COMMENT ON COLUMN registrations.study_languages IS
  '쓸 수 있는 언어(ISO 639-1). 첫 번째가 주 언어이며 study_language 와 같다.';
