-- 040: 현장 대표 연락처를 여러 명 둔다
--
-- 005 에서 두 명분을 컬럼으로 박아 뒀다(contact1_name/phone, contact2_...).
-- 실제 수양회에는 공항·숙소·차량을 나눠 맡는 사람이 그보다 많고, 참가자가
-- 급할 때 닿아야 할 번호가 둘로 끝나지 않는다.
--
-- 컬럼을 더 만들지 않는다. contact3, contact4… 로 늘리면 화면도 질의도
-- 그 수만큼 손봐야 한다. 목록 하나로 둔다:
--
--   [{"name": "Marcos Kim", "phone": "+54-11-3012-3113"}, …]
--
-- **005 의 두 컬럼은 그대로 둔다.** 이미 적어 둔 연락처가 들어 있고,
-- 옮기는 UPDATE 는 migrate.js 가 매 실행마다 다시 돌려 사용자가 그 뒤에
-- 고친 내용을 덮어쓴다. 서버가 읽을 때 비어 있으면 옛 컬럼에서 만들어 주고,
-- 저장할 때 앞의 두 명을 옛 컬럼에도 함께 적는다 — 그래야 옛 앱이 깔린
-- 기기에서도 연락처가 사라지지 않는다.
ALTER TABLE programs
  ADD COLUMN IF NOT EXISTS contacts JSONB DEFAULT '[]'::jsonb;
