-- 063: 투어가 열리는 최소 인원
--
-- 사람이 적으면 차도 가이드도 안 잡힌다. 셋이 안 되면 그 투어는 열리지
-- 않는다는 것이 지금까지 말로만 있던 규칙이고, 참가자는 신청하고 나서야
-- 알았다. **고르는 자리에서 미리 보여야 한다.**
--
-- 값을 칸으로 두는 이유는 투어마다 다르기 때문이다. 봉고차 한 대면 셋으로
-- 되지만 전세 버스를 잡아야 하는 투어는 여섯이 필요할 수 있다. 규칙을
-- 화면에 박아 두면 그때 코드를 고쳐야 한다.
--
-- 기본은 3 이다 — 지금 쓰는 규칙 그대로다. 1 로 두면 인원 제한이 없는 것과
-- 같으므로, 언제나 열리는 투어는 1 로 적으면 된다.
ALTER TABLE program_options
  ADD COLUMN IF NOT EXISTS min_signups INTEGER NOT NULL DEFAULT 3;

COMMENT ON COLUMN program_options.min_signups IS
  '이 인원이 모여야 투어가 열린다. 기본 3, 제한을 없애려면 1(063)';
