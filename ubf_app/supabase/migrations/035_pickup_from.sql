-- 035: 개최국 참석자에게는 "어디서 태울까" 만 묻는다
--
-- 개최국에서 오는 사람에게 항공편을 물을 이유가 없다. 버스로, 차로, 기차로
-- 온다. 필요한 것은 하나다 — **픽업이 필요한지, 필요하면 어디서.**
--
-- 지금까지 개최국 참석자는 항공편 스텝을 건너뛰고 픽업 명단에서도 빠졌다
-- (isPickupExempt). 그 판단의 근거는 "항공편이 없으니 공항에 안 온다" 였는데,
-- 공항이 아닌 곳에서 태워야 하는 사람이 있다는 사실은 물어본 적이 없어서
-- 아무 데도 남지 않았다.
--
-- 이제 물어본다. 적어 낸 사람은 항공편이 없어도 배차 명단에 남는다.
ALTER TABLE registrations
  ADD COLUMN IF NOT EXISTS pickup_from TEXT;

COMMENT ON COLUMN registrations.pickup_from IS
  '개최국 참석자가 태워 달라는 장소(버스터미널·지부·집 앞 등). 비어 있으면 공항 기준으로 본다.';
