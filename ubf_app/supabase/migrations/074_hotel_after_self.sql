-- 074: 수양회 뒤 숙소를 스스로 해결하는 사람
--
-- 수양회(와 투어)가 끝난 뒤 며칠 더 머무는 사람 중에는 우리가 잡아 주는
-- 호텔이 아니라 **자기가 직접 숙소를 찾아 묵는** 사람이 있다. 그 밤들에
-- 우리 돈이 들지 않으므로 숙박비를 받을 이유가 없다.
--
-- 지금까지는 그렇게 말할 길이 없었다. 묵을 밤이 있으면 화면이 "호텔이
-- 필요 없습니다" 를 일부러 감췄다 — 그것을 고르면 담당자는 그 사람이
-- 스스로 잡았다는 것인지 아직 안 정했다는 것인지 알 수 없기 때문이다(064).
-- 그래서 **"스스로 해결" 을 따로 적는 칸**을 둔다. 미정과 구별된다.
--
-- **박수는 그대로 둔다.** 비행 일정에서 나온 hotel_nights_after 는 지우지
-- 않는다 — 그 사람이 그 도시에 그만큼 더 있다는 사실은 공항 배웅을
-- 잡을 때 여전히 필요하다. 값을 매길 때만 뒤 박수를 뺀다.
--
-- 수양회 **앞** 박수에는 해당하지 않는다. 요청이 "수양회 이후" 였고,
-- 앞쪽은 도착 날 공항에서 바로 모셔 가므로 우리 호텔을 쓰는 것이 전제다.
ALTER TABLE registrations
  ADD COLUMN IF NOT EXISTS hotel_after_self BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN registrations.hotel_after_self IS
  'true 면 수양회 뒤 박수(hotel_nights_after)의 숙소를 본인이 해결한다. '
  '그 밤들에는 숙박비를 받지 않는다. 박수 자체는 그대로 남는다(074)';
