-- 045: 일정에 봉사 역할을 하나 잇는다
--
-- 일정 알림은 이미 시작 5분 전에 나간다. 거기에 "이 순서에 봉사자가 아직
-- 모자랍니다" 를 얹으면, 사람들이 가장 그 일을 떠올리는 순간에 손을 들 수
-- 있다. 따로 알림을 하나 더 만드는 것보다 낫다 — 알림이 늘어날수록 사람들은
-- 알림 자체를 끈다.
--
-- 하나만 잇는다. 한 순서에 식사 준비와 청소가 함께 필요할 수도 있지만,
-- 여럿을 붙이면 알림 한 통이 길어지고 버튼이 여럿이 된다. 먼저 하나로 두고
-- 모자라면 늘린다.
--
-- 값은 service_roles.js 의 역할 키다. 외래키를 걸 표가 없다(역할 구성은
-- programs.service_options 안의 JSON 이다).
ALTER TABLE program_schedules
  ADD COLUMN IF NOT EXISTS service_key TEXT;
