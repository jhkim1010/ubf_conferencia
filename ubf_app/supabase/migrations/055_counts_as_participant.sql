-- 055: 등록을 마친 사람은 이름이 비어 있어도 참가자로 센다
--
-- 038 이 "이름을 적은 등록만 명단에 넣는다" 를 한 곳에 모았다. 앱을 열면
-- 등록 행이 먼저 생기고 이름은 다음 화면에서 받으므로, 열어만 보고 만
-- 사람이 빈 행으로 남기 때문이다. 그 판단은 지금도 맞다.
--
-- 그런데 **등록을 끝까지 제출한 사람도 이름이 빌 수 있었다.** 제출 처리가
-- 이름을 확인하지 않았다. 운영 데이터에서 실제로 한 명이 그렇게 되었다 —
-- 나라·지부·성별·나이를 다 적고 제출까지 했는데 이름 칸만 비어서, 명단
-- 에도 대시보드 숫자에도 배정 대상에도 알림 대상에도 없었다. 담당자에게는
-- "등록한 사람이 14명인데 12로 나온다" 로 보였다.
--
-- 이름이 없다는 이유로 **사라지게** 두는 것이 문제다. 제출은 "나는
-- 참가한다" 는 분명한 뜻이므로, 이름이 비었으면 명단에 빈 이름으로라도
-- 나와야 담당자가 물어보고 채울 수 있다.
--
-- has_registrant_name 은 그대로 둔다. 준비 현황에서 "개인정보 단계를
-- 끝냈는가" 를 묻는 데 쓰이는데, 그것은 여기와 다른 질문이다.
CREATE OR REPLACE FUNCTION counts_as_participant(v text, submitted boolean)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT COALESCE(btrim(v), '') <> '' OR COALESCE(submitted, false)
$$;
